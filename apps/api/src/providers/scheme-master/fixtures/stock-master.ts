/**
 * SEBI/AMFI classify by rank on full market cap: 1–100 large, 101–250 mid,
 * 251+ small. We approximate the rank boundaries with capitalisation
 * thresholds because the fixture set is not the full listed universe. The
 * metadata sync job replaces this with the published AMFI classification list.
 */
export function classifyMarketCap(marketCapCrore: number): string {
  if (marketCapCrore >= 100_000) return 'LARGE_CAP';
  if (marketCapCrore >= 30_000) return 'MID_CAP';
  return 'SMALL_CAP';
}
